import { render, screen, waitFor } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { expect, it } from "vitest";
import { TeacherGradingPage } from "./page";

it("preserves grading drafts, validates scores, retains failed submissions and advances only on success", async () => {
  const user = userEvent.setup();
  render(<TeacherGradingPage />);
  const score = screen.getByRole("textbox", { name: "本题得分" });
  await user.click(screen.getByRole("button", { name: "保存并下一位" }));
  expect(screen.getByText("请输入 0–15 分，支持 0.5 分。")).toBeInTheDocument();
  expect(score).toHaveFocus();
  await user.click(screen.getByRole("button", { name: "12 分" }));
  await user.click(screen.getByText("添加常用评语", { selector: "summary" }));
  await user.click(screen.getByRole("button", { name: "添加评语：请补充适用条件" }));
  await user.click(screen.getByRole("button", { name: "下一位" }));
  expect(score).toHaveValue("");
  await user.click(screen.getByRole("button", { name: "上一位" }));
  expect(score).toHaveValue("12");
  expect(screen.getByRole("textbox", { name: "评语" })).toHaveValue("请补充适用条件。");
  await user.click(screen.getByRole("tab", { name: "按人批改" }));
  expect(screen.getByRole("heading", { name: "林知夏的作答" })).toBeInTheDocument();
  await user.click(screen.getByText("演示设置", { selector: "summary" }));
  await user.click(screen.getByRole("checkbox", { name: "下次保存失败" }));
  await user.click(screen.getByRole("button", { name: "保存并下一题" }));
  expect(screen.getByRole("button", { name: "下一题" })).toBeDisabled();
  await waitFor(() => expect(screen.getByRole("alert")).toHaveTextContent("保存失败"));
  expect(score).toHaveValue("12");
  await user.click(screen.getByRole("button", { name: "保存并下一题" }));
  await waitFor(() => expect(score).toHaveValue(""));
  expect(screen.getByRole("heading", { name: /第 3 题.*实验与误差/ })).toBeInTheDocument();
  expect(screen.getByRole("button", { name: "下一题" })).toBeDisabled();
  await user.click(screen.getByRole("button", { name: "上一题" }));
  expect(score).toHaveValue("12");
  await user.type(screen.getByRole("textbox", { name: "搜索学生或题目" }), "不存在");
  expect(screen.getByRole("heading", { name: "没有匹配的作答" })).toBeInTheDocument();
  await user.click(screen.getByRole("button", { name: "清空筛选" }));
  expect(screen.getByRole("heading", { name: "林知夏的作答" })).toBeInTheDocument();
});

it("keeps zero scores and grading state inside their paper, and supports keyboard mode selection", async () => {
  const user = userEvent.setup();
  render(<TeacherGradingPage />);
  await user.click(screen.getByRole("tab", { name: "B 卷" }));
  const score = () => screen.getByRole("textbox", { name: "本题得分" });
  await user.type(score(), "0");
  await user.click(screen.getByRole("button", { name: "保存" }));
  await waitFor(() => expect(screen.getByText("已保存")).toBeInTheDocument());
  await user.click(screen.getByRole("tab", { name: "A 卷" }));
  expect(score()).toHaveValue("");
  await user.click(screen.getByRole("tab", { name: "B 卷" }));
  expect(score()).toHaveValue("0");
  screen.getByRole("tab", { name: "按题批改" }).focus();
  await user.keyboard("{ArrowRight}");
  expect(screen.getByRole("tab", { name: "按人批改" })).toHaveFocus();
  await user.keyboard("{Enter}");
  expect(screen.getByRole("tab", { name: "按人批改" })).toHaveAttribute("aria-selected", "true");
  expect(score()).toHaveValue("0");
});
