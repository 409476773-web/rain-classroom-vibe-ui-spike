// Compile Bklit's static utilities once, scoped to chart hosts. No global Tailwind reset.
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { createRequire } from "node:module";
import { compile } from "tailwindcss";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const shared = resolve(root, "packages/ui/src/charts");
const base = existsSync(resolve(shared, "vendor")) ? shared : resolve(root, "apps/prototype/src/scenarios/bklit-validation");
const postcss = createRequire(import.meta.resolve("vite"))("postcss");
const texts = [];
function scan(dir) {
  for (const item of readdirSync(dir, { withFileTypes: true })) {
    const path = resolve(dir, item.name);
    if (item.isDirectory()) scan(path);
    else if (/\.(ts|tsx)$/.test(path)) texts.push(readFileSync(path, "utf8"));
  }
}
scan(resolve(base, "vendor"));
texts.push(readFileSync(resolve(root, "packages/ui/src/breadcrumb/breadcrumb.tsx"), "utf8"));
const candidates = new Set();
for (const text of texts) {
  for (const match of text.matchAll(/(?:"([^"\n]*)"|'([^'\n]*)'|`([^`]*)`)/g)) {
    for (const word of (match[1] ?? match[2] ?? match[3]).split(/\s+/)) {
      if (word && !word.includes("${")) candidates.add(word);
    }
  }
}
const theme = readFileSync(new URL("../theme.css", import.meta.resolve("tailwindcss")), "utf8");
const rainTheme = readFileSync(resolve(root, "packages/foundations/src/tailwind-theme.css"), "utf8");
const roles = ["background", "foreground", "border", "muted", "muted-foreground", "popover", "popover-foreground", "chart-label", "chart-foreground", "chart-foreground-muted", "chart-tooltip-background", "chart-tooltip-foreground", "chart-tooltip-muted", "legend", "legend-foreground", "legend-muted", "legend-muted-foreground", "legend-track"];
const compiler = await compile(`${rainTheme}\n${theme}\n@theme inline { ${roles.map(r => `--color-${r}: var(--${r});`).join(" ")} }\n@tailwind utilities;`);
const css = postcss.parse(compiler.build([...candidates]));
css.walkAtRules("property", rule => rule.remove());
css.walkRules(rule => {
  if (rule.parent?.type === "atrule" && /keyframes$/.test(rule.parent.name)) return;
  if (rule.selector.includes(":root") || rule.selector.includes(":host")) rule.selector = ":where(.rain-chart)";
  else if (rule.selector.includes("&")) return; // Nested rules inherit the scoped parent.
  else rule.selector = rule.selectors.map(s => `:where(.rain-chart) ${s}`).join(", ");
});
const header = "/* GENERATED by node scripts/generate-chart-styles.mjs. Bklit static geometry, chart scope only. */\n";
const output = resolve(base, "utilities.generated.css");
const value = header + css.toString() + "\n";
if (process.argv.includes("--check")) {
  if (!existsSync(output) || readFileSync(output, "utf8") !== value) throw new Error("Chart utilities need regeneration");
} else writeFileSync(output, value);
console.log(`Chart utilities ${process.argv.includes("--check") ? "verified" : "generated"}: ${candidates.size} scanned candidates`);
