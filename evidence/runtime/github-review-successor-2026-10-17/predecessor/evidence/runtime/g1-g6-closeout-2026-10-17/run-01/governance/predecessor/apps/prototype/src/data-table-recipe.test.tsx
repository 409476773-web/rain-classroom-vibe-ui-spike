import "@testing-library/jest-dom/vitest";
import { render, screen, within } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { expect, it } from "vitest";
import { DataTableRecipe } from "./data-table-recipe";

it("uses the shared data pager for totals, capacity and jumps without losing selection", async () => {
  const user = userEvent.setup();
  render(<DataTableRecipe />);
  const nav = screen.getByRole("navigation", { name: "分页" });
  expect(nav.querySelector('[data-slot="total"]')).toHaveTextContent("共 13 条");
  expect(screen.queryByRole("combobox", { name: "每页数量" })).not.toBeInTheDocument();
  expect(screen.queryByRole("button", { name: "取消选择" })).not.toBeInTheDocument();
  expect(screen.getByRole("button", { name: "标为已发布" })).toBeDisabled();
  expect(screen.getByRole("button", { name: "标为已发布" })).toHaveAttribute("data-variant", "primary");
  await user.click(screen.getByRole("checkbox", { name: "选择 设计方法导论" }));
  expect(within(screen.getByRole("group", { name: "资料操作" })).getAllByRole("button").map(button => button.getAttribute("aria-label") || button.textContent)).toEqual(["选择规则说明", "刷新资料", "显示列", "取消选择", "标为已发布"]);
  expect(screen.getByRole("button", { name: "取消选择" })).toHaveAttribute("data-variant", "tertiary");
  await user.click(within(nav).getByRole("button", { name: "第 3 页" }));
  expect(screen.getByText("含其他页 1 份")).toBeInTheDocument();
  await user.click(within(nav).getByRole("button", { name: "分页设置" }));
  await user.click(screen.getByRole("button", { name: "每页 10 条" }));
  expect(within(nav).getByRole("button", { name: "第 2 页" })).toHaveAttribute("aria-current", "page");
  expect(screen.getByRole("cell", { name: "课堂活动设计" })).toBeInTheDocument();
  expect(screen.getByText("已选 1 份资料")).toBeInTheDocument();
  await user.click(within(nav).getByRole("button", { name: "分页设置" }));
  await user.type(screen.getByRole("textbox", { name: "跳转到页码" }), "1");
  await user.click(screen.getByRole("button", { name: /^跳转$/ }));
  expect(screen.getByRole("checkbox", { name: "选择 设计方法导论" })).toBeChecked();
  await user.click(screen.getByRole("button", { name: "卡片视图" }));
  expect(within(nav).getByRole("button", { name: "分页设置" })).toHaveTextContent("10");
  await user.click(screen.getByRole("button", { name: "取消选择" }));
  expect(screen.queryByText("已选 0 份资料")).not.toBeInTheDocument();
  expect(screen.queryByRole("button", { name: "取消选择" })).not.toBeInTheDocument();
  expect(screen.getByRole("checkbox", { name: "选择 设计方法导论" })).not.toBeChecked();
  expect(screen.getByRole("button", { name: "标为已发布" })).toBeDisabled();
});

