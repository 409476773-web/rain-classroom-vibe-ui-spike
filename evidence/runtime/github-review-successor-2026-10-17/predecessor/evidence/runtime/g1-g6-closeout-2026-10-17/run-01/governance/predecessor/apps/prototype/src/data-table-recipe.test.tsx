it("selects only actionable rows on the current page and clears no-results queries", async () => {
  const user = userEvent.setup();
  render(<DataTableRecipe />);
  const selectPage = screen.getByRole("checkbox", { name: "选择当前页可操作资料" });
  await user.click(selectPage);
  expect(screen.getByText("已选 4 份资料")).toBeInTheDocument();
  expect(screen.getByRole("checkbox", { name: "选择 课堂观察记录" })).toBeDisabled();
  await user.click(screen.getByRole("button", { name: "下一页" }));
  expect(screen.getByRole("checkbox", { name: "选择当前页可操作资料" })).not.toBeChecked();
  await user.type(screen.getByRole("textbox", { name: "查找资料" }), "不存在的资料");
  await user.click(screen.getByRole("button", { name: "搜索" }));
  expect(screen.getByRole("heading", { name: "没有找到相关资料" })).toBeInTheDocument();
  await user.click(screen.getByRole("button", { name: "清空筛选" }));
  expect(screen.getByRole("checkbox", { name: "选择 设计方法导论" })).not.toBeChecked();
});

it("shows clear only for applied filters and resets query, status, page and selection together", async () => {
  const user = userEvent.setup();
  render(<DataTableRecipe />);
  const search = screen.getByRole("textbox", { name: "查找资料" });
  const clear = () => screen.queryByRole("button", { name: "清空筛选" });
  expect(clear()).not.toBeInTheDocument();
  await user.type(search, "教学案例");
  expect(clear()).not.toBeInTheDocument();
  await user.click(screen.getByRole("button", { name: "搜索" }));
  expect(clear()).toBeInTheDocument();
  await user.click(screen.getByText("发布状态", { exact: true }));
  await user.click(await screen.findByRole("option", { name: "草稿" }));
  await user.click(screen.getByRole("checkbox", { name: "选择 教学案例研读" }));
  await user.click(clear()!);
  expect(search).toHaveValue("");
  expect(search).toHaveFocus();
  expect(screen.getByRole("combobox", { name: "发布状态" })).toHaveTextContent("全部状态");
  expect(clear()).not.toBeInTheDocument();
  expect(screen.queryByText("已选 0 份资料")).not.toBeInTheDocument();
  expect(screen.getByRole("navigation", { name: "分页" })).toHaveTextContent("共 13 条");
  await user.click(screen.getByText("发布状态", { exact: true }));
  await user.click(await screen.findByRole("option", { name: "草稿" }));
  expect(clear()).toBeInTheDocument();
  await user.click(screen.getByRole("button", { name: "下一页" }));
  await user.click(clear()!);
  expect(screen.getByRole("button", { name: "上一页" })).toBeDisabled();
  expect(clear()).not.toBeInTheDocument();
});

it("keeps card selection checkbox-only with matching fields, menus, page selection and sorting", async () => {
  const user = userEvent.setup();
  render(<DataTableRecipe />);
  const more = () => screen.getByRole("button", { name: "更多操作 设计方法导论" });
  expect(more()).toHaveAttribute("data-tone", "brand");
  await user.click(screen.getByRole("checkbox", { name: "选择 设计方法导论" }));
  await user.click(screen.getByRole("button", { name: "卡片视图" }));
  const card = screen.getByRole("article", { name: "设计方法导论" });
  const selected = within(card).getByRole("checkbox");
  expect(selected).toBeChecked();
  expect(card).toHaveAttribute("data-selected", "true");
  expect(within(card).getByText("阅读材料").closest('[data-rain-id="ui-tag"]')).toHaveAttribute("data-appearance", "outlined");
  expect(within(card).getByText("已发布").closest('[data-rain-id="ui-tag"]')).toHaveAttribute("data-color", "classroom");
  expect(within(card).getByText("更新于 2026-09-13").tagName).toBe("TIME");
  await user.click(card);
  await user.click(within(card).getByRole("heading"));
  await user.click(within(card).getByText("阅读材料"));
  await user.click(more());
  expect(more()).toHaveAttribute("data-rain-id", "ui-icon-button");
  await user.click(await screen.findByRole("menuitem", { name: "查看资料" }));
  expect(screen.getByRole("status")).toHaveTextContent("正在查看《设计方法导论》");
  expect(selected).toBeChecked();
  await user.click(screen.getByRole("button", { name: "更多操作 课堂观察记录" }));
  expect(await screen.findByRole("menuitem", { name: /记录稍后处理/ })).toHaveAttribute("aria-disabled", "true");
  await user.keyboard("{Escape}");
  expect(screen.getByRole("checkbox", { name: "选择 课堂观察记录" })).toHaveAccessibleDescription("只读资料，不参与批量操作");
  const selectPage = () => screen.getByRole("checkbox", { name: "选择当前页可操作资料" });
  expect(selectPage()).toHaveAttribute("aria-checked", "mixed");
  await user.click(selectPage());
  expect(screen.getByText("已选 4 份资料")).toBeInTheDocument();
  await user.click(screen.getByRole("button", { name: "下一页" }));
  await user.click(selectPage());
  expect(screen.getByText("已选 9 份资料")).toBeInTheDocument();
  await user.click(screen.getByRole("button", { name: "上一页" }));
  await user.click(selectPage());
  expect(screen.getByText("已选 5 份资料")).toBeInTheDocument();
  await user.click(screen.getByRole("button", { name: "按资料名称排序" }));
  await user.click(await screen.findByRole("menuitemradio", { name: "资料名称 · 升序" }));
  expect(screen.getByRole("button", { name: "按资料名称排序" })).toHaveTextContent("升序");
  await user.click(screen.getByRole("button", { name: "表格视图" }));
  expect(screen.getByRole("button", { name: "按资料名称排序" }).closest("th")).toHaveAttribute("aria-sort", "ascending");
  expect(screen.getByText("已选 5 份资料")).toBeInTheDocument();
});
