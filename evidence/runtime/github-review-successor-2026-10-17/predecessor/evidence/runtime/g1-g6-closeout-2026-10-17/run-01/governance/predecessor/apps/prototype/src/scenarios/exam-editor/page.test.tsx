import { render, screen, waitFor, within } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { expect, it, vi } from "vitest";
import { ExamEditorPage } from "./page";

it("opens the shared move dialog, commits a batch in source order, and supports undo", async () => {
  vi.stubGlobal("IntersectionObserver", class { observe() {} disconnect() {} });
  HTMLElement.prototype.scrollIntoView = vi.fn();
  const user = userEvent.setup();
  render(<ExamEditorPage />);
  await user.click(within(screen.getByRole("article", { name: "第 1 题 单选题" })).getByRole("button", { name: "移动到" }));
  expect(await screen.findByRole("dialog", { name: "选择习题移动的位置" })).toBeInTheDocument();
  expect(within(screen.getByRole("dialog")).getByText("1. 单选题", { exact: true })).toBeInTheDocument();
  expect(screen.getByRole("button", { name: "确认移动" })).toBeDisabled();
  expect(screen.getByRole("radio", { name: /^第 1 题.*单选题/ })).toBeEnabled();
  expect(screen.getByRole("combobox", { name: "插入位置" })).toBeDisabled();
  expect(screen.getByText("请选择参照题")).toBeInTheDocument();
  expect(within(screen.getByRole("dialog")).getAllByText("应用")[0]!).toBeInTheDocument();
  await user.click(screen.getByRole("radio", { name: /^第 1 题.*单选题/ }));
  expect(screen.getByRole("dialog").querySelector(".em-move-destination")).toHaveTextContent("将 1 道习题移动到 第 1 题处");
  expect(screen.getByText("已在此位置，无需移动")).toBeInTheDocument();
  expect(screen.getByRole("button", { name: "确认移动" })).toBeDisabled();
  expect(screen.queryByRole("combobox", { name: "插入位置" })).not.toBeInTheDocument();
  expect(screen.getByRole("dialog").querySelector(".em-insert-line, .em-gather-preview")).toBeNull();
  await user.keyboard("{Escape}");
  await waitFor(() => expect(screen.queryByRole("dialog")).not.toBeInTheDocument());
  await user.click(screen.getByRole("checkbox", { name: "选择第 4 题" }));
  await user.click(screen.getByRole("checkbox", { name: "选择第 2 题" }));
  await user.click(screen.getByRole("button", { name: "批量移动" }));
  await user.type(screen.getByRole("textbox", { name: "搜索目标题" }), "8");
  expect(screen.getAllByRole("radio")).toHaveLength(1);
  await user.click(await screen.findByRole("radio", { name: /^第 8 题.*单选题/ }));
  expect(screen.getByRole("tab", { name: "默认" })).toHaveAttribute("aria-selected", "true");
  for (const mode of ["紧凑", "宽松", "默认"]) {
    await user.click(screen.getByRole("tab", { name: mode }));
    expect(screen.getByRole("tab", { name: mode })).toHaveAttribute("aria-selected", "true");
    expect(screen.getByRole("radio", { name: /^第 8 题.*单选题/ })).toBeChecked();
    expect(screen.getByRole("textbox", { name: "搜索目标题" })).toHaveValue("8");
  }
  const position = screen.getByRole("combobox", { name: "插入位置" });
  expect(position).toHaveTextContent("之后");
  await user.click(position);
  await user.click(await screen.findByRole("option", { name: "之前" }));
  expect(position).toHaveTextContent("之前");
  await user.click(screen.getByRole("button", { name: "确认移动" }));
  await waitFor(() => expect(screen.queryByRole("dialog")).not.toBeInTheDocument());
  expect(screen.getAllByRole("article").slice(5, 7).map(q => q.id)).toEqual(["exam-r1", "exam-m1"]);
  expect(screen.getByRole("spinbutton", { name: "第 6 题分值" })).toHaveValue("6");
  expect(screen.getByText("已移动 2 道习题")).toBeInTheDocument();
  await user.click(screen.getByRole("button", { name: "撤销" }));
  expect(screen.getAllByRole("article").slice(0, 4).map(q => q.id)).toEqual(["exam-s1", "exam-r1", "exam-s2", "exam-m1"]);
  vi.unstubAllGlobals();
});

it("gathers a reverse-selected scattered batch around its selected reference and supports cancel and undo", async () => {
  vi.stubGlobal("IntersectionObserver", class { observe() {} disconnect() {} });
  HTMLElement.prototype.scrollIntoView = vi.fn();
  const user = userEvent.setup();
  render(<ExamEditorPage />);
  const original = screen.getAllByRole("article").map(q => q.id);
  for (const number of [6, 4, 2]) await user.click(screen.getByRole("checkbox", { name: `选择第 ${number} 题` }));
  await user.click(screen.getByRole("button", { name: "批量移动" }));
  await user.click(screen.getByRole("radio", { name: /^第 4 题.*多选题/ }));
  expect(screen.getByRole("dialog").querySelector(".em-move-destination")).toHaveTextContent("将 3 道习题移动到 第 4 题处");
  expect(screen.getByText("3 道习题将移动到这里")).toBeInTheDocument();
  expect(screen.getByRole("dialog").querySelector(".em-move-feedback")).toBeNull();
  expect(screen.queryByRole("combobox", { name: "插入位置" })).not.toBeInTheDocument();
  expect(screen.getByRole("dialog").querySelector(".em-insert-line")).toBeNull();
  await user.click(within(screen.getByRole("dialog")).getByRole("button", { name: "取消" }));
  await waitFor(() => expect(screen.queryByRole("dialog")).not.toBeInTheDocument());
  expect(screen.getAllByRole("article").map(q => q.id)).toEqual(original);
  for (const number of [2, 4, 6]) expect(screen.getByRole("checkbox", { name: `选择第 ${number} 题` })).toBeChecked();
  await user.click(screen.getByRole("button", { name: "批量移动" }));
  await user.click(screen.getByRole("radio", { name: /^第 8 题.*单选题/ }));
  await user.click(screen.getByRole("combobox", { name: "插入位置" }));
  await user.click(await screen.findByRole("option", { name: "之前" }));
  await user.click(screen.getByRole("radio", { name: /^第 4 题.*多选题/ }));
  expect(screen.queryByRole("combobox", { name: "插入位置" })).not.toBeInTheDocument();
  await user.click(screen.getByRole("radio", { name: /^第 8 题.*单选题/ }));
  expect(screen.getByRole("combobox", { name: "插入位置" })).toHaveTextContent("之前");
  await user.click(screen.getByRole("radio", { name: /^第 4 题.*多选题/ }));
  await user.click(screen.getByRole("button", { name: "确认移动" }));
  await waitFor(() => expect(screen.queryByRole("dialog")).not.toBeInTheDocument());
  expect(screen.getAllByRole("article").slice(0, 7).map(q => q.id)).toEqual(["exam-s1", "exam-s2", "exam-r1", "exam-m1", "exam-s3", "exam-w1", "exam-s4"]);
  expect(screen.getByRole("spinbutton", { name: "第 3 题分值" })).toHaveValue("6");
  expect(screen.getByRole("spinbutton", { name: "第 4 题分值" })).toHaveValue("4");
  expect(screen.getByText("已移动 3 道习题")).toBeInTheDocument();
  await user.click(screen.getByRole("button", { name: "撤销" }));
  expect(screen.getAllByRole("article").map(q => q.id)).toEqual(original);
  vi.unstubAllGlobals();
});

it("keeps no-op feedback consistent for adjacent references, continuous selections and the whole paper", async () => {
  vi.stubGlobal("IntersectionObserver", class { observe() {} disconnect() {} });
  HTMLElement.prototype.scrollIntoView = vi.fn();
  const user = userEvent.setup();
  render(<ExamEditorPage />);
  for (const number of [1, 2]) await user.click(screen.getByRole("checkbox", { name: `选择第 ${number} 题` }));
  await user.click(screen.getByRole("button", { name: "批量移动" }));
  await user.click(screen.getByRole("radio", { name: /^第 3 题.*单选题/ }));
  await user.click(screen.getByRole("combobox", { name: "插入位置" }));
  await user.click(await screen.findByRole("option", { name: "之前" }));
  expect(screen.getByText("已在此位置，无需移动")).toBeInTheDocument();
  expect(screen.getByRole("button", { name: "确认移动" })).toBeDisabled();
  expect(screen.getByRole("dialog").querySelector(".em-insert-line, .em-gather-preview")).toBeNull();
  await user.click(screen.getByRole("radio", { name: /^第 2 题.*材料题/ }));
  expect(screen.getByText("已在此位置，无需移动")).toBeInTheDocument();
  expect(screen.queryByRole("combobox", { name: "插入位置" })).not.toBeInTheDocument();
  await user.keyboard("{Escape}");
  await waitFor(() => expect(screen.queryByRole("dialog")).not.toBeInTheDocument());
  await user.click(screen.getByRole("button", { name: "取消选择" }));
  await user.click(screen.getByRole("checkbox", { name: "全选习题" }));
  await user.click(screen.getByRole("button", { name: "批量移动" }));
  expect(screen.getAllByRole("radio")).toHaveLength(40);
  screen.getAllByRole("radio").forEach(radio => expect(radio).toBeEnabled());
  await user.click(screen.getByRole("radio", { name: /^第 20 题/ }));
  expect(screen.getByText("已在此位置，无需移动")).toBeInTheDocument();
  expect(screen.getByRole("button", { name: "确认移动" })).toBeDisabled();
  expect(screen.getByRole("dialog").querySelector(".em-insert-line, .em-gather-preview")).toBeNull();
  vi.unstubAllGlobals();
});

it("opens import choices on hover and completes template and question-bank imports", async () => {
  vi.stubGlobal("IntersectionObserver", class { observe() {} disconnect() {} });
  HTMLElement.prototype.scrollIntoView = vi.fn();
  const user = userEvent.setup();
  render(<ExamEditorPage />);
  const importButton = screen.getByRole("button", { name: "导入习题" });
  await user.hover(importButton);
  expect(await screen.findByRole("menuitem", { name: "模板导入" })).toBeInTheDocument();
  await user.click(screen.getByRole("menuitem", { name: "模板导入" }));
  expect(await screen.findByRole("dialog", { name: "模板导入" })).toBeInTheDocument();
  const file = new File(["题型,题干\n单选题,示例"], "习题模板.xlsx", { type: "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet" });
  await user.upload(screen.getByLabelText("选择 Excel 模板"), file);
  expect(screen.getByText("习题模板.xlsx")).toBeInTheDocument();
  await user.click(screen.getByRole("button", { name: "导入习题" }));
  await waitFor(() => expect(screen.queryByRole("dialog", { name: "模板导入" })).not.toBeInTheDocument());
  expect(screen.getByRole("status")).toHaveTextContent("已从模板导入 3 道习题");

  await user.hover(importButton);
  await user.click(await screen.findByRole("menuitem", { name: "题库导入" }));
  expect(await screen.findByRole("dialog", { name: "题库导入" })).toBeInTheDocument();
  await user.click(screen.getByRole("checkbox", { name: "选择题库习题 1" }));
  await user.click(screen.getByRole("button", { name: "导入 1 道习题" }));
  await waitFor(() => expect(screen.queryByRole("dialog", { name: "题库导入" })).not.toBeInTheDocument());
  expect(screen.getByRole("status")).toHaveTextContent("已从题库导入 1 道习题");
  vi.unstubAllGlobals();
});
