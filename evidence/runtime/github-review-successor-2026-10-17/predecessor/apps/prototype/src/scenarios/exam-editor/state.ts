export function moveQuestions<T extends { id: string }>(items: T[], ids: string[], target: string, side: "before" | "after"): T[] {
  const selected = new Set(ids);
  const targetIndex = items.findIndex(q => q.id === target);
  if (!ids.length || targetIndex === -1) return items;
  const moving = items.filter(q => selected.has(q.id));
  if (!moving.length) return items;
  const rest = items.filter(q => !selected.has(q.id));
  // A selected reference's two original gaps converge after removal, keeping its position.
  const index = items.slice(0, targetIndex + (side === "after" ? 1 : 0)).filter(q => !selected.has(q.id)).length;
  const result = [...rest.slice(0, index), ...moving, ...rest.slice(index)];
  return result.every((q, i) => q === items[i]) ? items : result;
}

