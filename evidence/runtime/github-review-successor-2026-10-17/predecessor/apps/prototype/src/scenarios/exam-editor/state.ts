export function createQuestions(): Question[] {
  const choice = (rows: typeof singles, type: Question["type"], prefix: string, score: number) => rows.map(([stem, options, answer, topic], i) => ({ id: `${prefix}${i + 1}`, type, stem, options, answer, topic, difficulty: i % 3 + 2, score, analysis: `结合${topic}，逐项判断题目给出的条件。参考答案为 ${answer}。` }));
  const s = choice(singles, "单选题", "s", 2), m = choice(multiple, "多选题", "m", 4);
  const w: Question[] = written.map(([stem, topic], i) => ({ id: `w${i + 1}`, type: "主观题", stem, topic, difficulty: 3, score: 5, answer: "按关键概念、分析过程和计算结果分别给分。", analysis: "参考评分：概念准确、步骤完整、结论合理。" }));
  const r: Question[] = materials.map(([stem, topic], i) => ({ id: `r${i + 1}`, type: "材料题", stem, topic, difficulty: 4, score: 6, answer: "结合材料列出关系式，并写出完整计算过程。", analysis: "本题结合两道小题的分析过程与计算结果评分。" }));
  return [s[0]!, r[0]!, s[1]!, m[0]!, w[0]!, ...s.slice(2), ...m.slice(1), ...w.slice(1), ...r.slice(1)];
}
