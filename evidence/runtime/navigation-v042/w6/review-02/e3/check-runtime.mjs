import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import assert from 'node:assert/strict';
import { chromium } from '@playwright/test';

const out = path.dirname(fileURLToPath(import.meta.url));
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1343, height: 747 }, locale: 'zh-CN', reducedMotion: 'reduce' });
const faults = [];
page.on('pageerror', error => faults.push(error.message));
page.on('response', response => { if (response.status() >= 400) faults.push(`${response.status()} ${response.url()}`); });
try {
  await page.goto('http://127.0.0.1:5204/navigation-v042-w6-consumer.html#E3');
  await page.locator('[data-scene="E3"] [data-rain-id="layout-connected-surface"][data-measured="true"]').waitFor();
  const questionTabs = page.getByRole('tablist', { name: '当前题目选择', exact: true });
  const q1 = questionTabs.getByRole('tab', { name: '第1题', exact: true }), q2 = questionTabs.getByRole('tab', { name: '第2题', exact: true });
  await page.getByRole('textbox', { name: '评分评语' }).fill('第一题的本地意见');
  await q1.focus();
  await page.keyboard.press('ArrowRight');
  assert.equal(await q1.getAttribute('aria-selected'), 'true');
  assert(await q2.evaluate(node => node === document.activeElement));
  await page.keyboard.press('Enter');
  assert.equal(await q2.getAttribute('aria-selected'), 'true');
  assert((await page.getByRole('tabpanel').textContent()).includes('设计控制变量'));
  assert.equal(await page.getByRole('textbox', { name: '评分评语' }).inputValue(), '');
  const score = page.getByRole('spinbutton', { name: '本题分数' }), save = page.getByRole('button', { name: '保存本地草稿' });
  await score.fill('17');
  await page.getByRole('textbox', { name: '评分评语' }).fill('第二题的本地意见');
  await page.getByRole('button', { name: '显示批改队列' }).click();
  await page.getByRole('radio', { name: '按题', exact: true }).locator('..').click();
  const queueMeasurements = await page.locator('[data-scene="E3"] .w6-grade-queue').evaluate(queue => {
    const nav = queue.querySelector('.rain-object-navigator'), rows = [...nav.querySelectorAll('.rain-navigation-family__row')];
    const bounds = queue.getBoundingClientRect();
    return { top: bounds.top, bottom: bounds.bottom, clientHeight: queue.clientHeight, scrollHeight: queue.scrollHeight, scrollTop: queue.scrollTop, rows: rows.map(row => { const box = row.getBoundingClientRect(); return { label: row.textContent, top: box.top, bottom: box.bottom, height: box.height }; }), fullScoreTags: nav.querySelectorAll('.rain-tag').length, modeControlHeights: [...queue.querySelectorAll('.rain-segmented-control')].map(control => control.getBoundingClientRect().height) };
  });
  assert.equal(queueMeasurements.rows.length, 3);
  assert.equal(queueMeasurements.scrollTop, 0);
  assert(queueMeasurements.rows[2].bottom <= queueMeasurements.bottom);
  assert(queueMeasurements.rows.every(row => row.height >= 76));
  assert.equal(queueMeasurements.fullScoreTags, 0);
  assert(queueMeasurements.modeControlHeights.every(height => height >= 32));
  await page.screenshot({ path: path.join(out, 'E3-queue-question-1343x747.png'), fullPage: true });
  const studentTabs = page.getByRole('tablist', { name: '当前学生选择', exact: true });
  await studentTabs.getByRole('tab', { name: '陈安', exact: true }).click();
  assert.equal(await score.inputValue(), '');
  await studentTabs.getByRole('tab', { name: '林宁', exact: true }).click();
  assert.equal(await score.inputValue(), '17');
  assert.equal(await page.getByRole('textbox', { name: '评分评语' }).inputValue(), '第二题的本地意见');
  await page.getByRole('radio', { name: '按人', exact: true }).locator('..').click();
  await page.getByRole('button', { name: '隐藏批改队列' }).click();
  await page.waitForFunction(() => {
    const surface = document.querySelector('[data-scene="E3"] [data-rain-id="layout-connected-surface"]');
    return surface && Number(surface.querySelector('svg').getAttribute('viewBox')?.split(' ')[2]) === surface.offsetWidth;
  });
  assert.equal(await q2.getAttribute('aria-selected'), 'true');
  assert(await page.getByText('尚未保存到本地', { exact: true }).isVisible());
  const measurements = await page.locator('[data-scene="E3"] .w6-grading-workspace').evaluate(workspace => {
    const heading = workspace.querySelector('.w6-grade-answer-heading h1'), meta = workspace.querySelector('.w6-grade-identity-meta'), surface = workspace.querySelector('[data-rain-id="layout-connected-surface"]');
    const number = workspace.querySelector('[data-rain-id="ui-input-number"]'), numericControl = number.querySelector('[role="spinbutton"]'), numberFrame = number.querySelector('[data-slot="frame"]'), comment = workspace.querySelector('[data-rain-id="ui-textarea"]');
    const h = heading.getBoundingClientRect(), m = meta.getBoundingClientRect(), n = number.getBoundingClientRect();
    return { title: { fontSize: getComputedStyle(heading).fontSize, lineHeight: getComputedStyle(heading).lineHeight, height: h.height }, metadata: { sameRowCenterDelta: Math.abs(h.y + h.height / 2 - m.y - m.height / 2), right: m.right, rowRight: meta.parentElement.getBoundingClientRect().right }, number: { width: n.width, appearance: number.dataset.appearance, fullWidth: number.dataset.fullWidth, numericControlWidth: numericControl.getBoundingClientRect().width, background: getComputedStyle(numberFrame).backgroundColor }, comment: { appearance: comment.dataset.appearance, background: getComputedStyle(comment).backgroundColor }, tabs: { preset: workspace.querySelector('.w6-grade-shortcuts').dataset.visualPreset, measured: surface.dataset.measured, activeVisible: surface.dataset.activeVisible, unionFill: getComputedStyle(surface.querySelector('path')).fill, path: surface.querySelector('path').getAttribute('d'), visiblePanelCount: [...workspace.querySelectorAll('[role="tabpanel"]')].filter(p => !p.hidden).length } };
  });
  assert.equal(measurements.title.fontSize, '16px');
  assert.equal(measurements.title.lineHeight, '22px');
  assert.equal(measurements.title.height, 22);
  assert(measurements.metadata.sameRowCenterDelta <= 1);
  assert(measurements.number.width < 200);
  assert.equal(measurements.number.fullWidth, 'false');
  assert.equal(measurements.number.appearance, 'filled');
  assert.equal(measurements.comment.appearance, 'filled');
  assert.equal(measurements.tabs.preset, 'navigation-browser');
  assert.equal(measurements.tabs.unionFill, 'rgb(255, 255, 255)');
  assert(measurements.tabs.path.length > 0);
  assert.equal(measurements.tabs.visiblePanelCount, 1);
  await page.screenshot({ path: path.join(out, 'E3-1343x747.png'), fullPage: true });
  await page.setViewportSize({ width: 996, height: 600 });
  const before = await score.boundingBox();
  const scrollTop = await page.locator('[data-scene="E3"] .w6-grade-main').evaluate(main => { main.scrollTop = 180; return main.scrollTop; });
  const after = await score.boundingBox();
  assert(scrollTop > 0);
  assert.equal(before.y, after.y);
  assert(await page.getByText('尚未保存到本地', { exact: true }).isVisible());
  await page.screenshot({ path: path.join(out, 'E3-996x600.png'), fullPage: true });
  assert.deepEqual(faults, []);
  fs.writeFileSync(path.join(out, 'runtime-check.json'), JSON.stringify({ status: 'passed', engine: 'chromium', sourceUrl: page.url(), faults, measurements, queueMeasurements, keyboard: 'manual focus does not activate; Enter activates real content panel', business: 'student/question drafts and explicit-only save retained', shortHeight: { scrollTop, scoreYBefore: before.y, scoreYAfter: after.y } }, null, 2));
  console.log(JSON.stringify({ status: 'passed', measurements, queueMeasurements, scrollTop, faults }));
} finally { await browser.close(); }
