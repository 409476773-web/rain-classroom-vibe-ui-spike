import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import { fileURLToPath } from 'node:url';
import { chromium } from '@playwright/test';

const out = path.dirname(fileURLToPath(import.meta.url));
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1338, height: 796 }, locale: 'zh-CN', reducedMotion: 'reduce' });
const faults = [];
page.on('pageerror', error => faults.push(error.message));
page.on('response', response => { if (response.status() >= 400) faults.push(`${response.status()} ${response.url()}`); });
const findings = { grading: {}, replay: {} };
try {
  await page.goto('http://127.0.0.1:5204/navigation-v042-w6-consumer.html#E3');
  await page.getByRole('spinbutton', { name: '本题分数' }).waitFor();
  const score = page.getByRole('spinbutton', { name: '本题分数' }), save = page.getByRole('button', { name: '保存本地草稿' });
  await score.fill('21');
  assert(await save.isDisabled());
  await page.getByRole('group', { name: '当前题目选择', exact: true }).getByRole('button', { name: '第2题', exact: true }).click();
  assert.equal(await score.inputValue(), '');
  assert(await save.isEnabled());
  await score.fill('12');
  await page.getByRole('group', { name: '当前题目选择', exact: true }).getByRole('button', { name: '第1题', exact: true }).click();
  assert.equal(await score.inputValue(), '21');
  assert(await save.isDisabled());
  await score.fill('14');
  assert(await save.isEnabled());
  await save.click();
  await page.getByText('已保存到本地状态', { exact: true }).waitFor();
  const q3 = page.getByRole('group', { name: '当前题目选择', exact: true }).getByRole('button', { name: '第3题', exact: true });
  await q3.click();
  assert(await save.isEnabled());
  findings.grading = await page.locator('[data-scene="E3"] .w6-grade-main').evaluate(main => {
    const workspace = main.closest('.rain-workspace'), scorePanel = workspace.querySelector('.w6-grade-score');
    const heading = main.querySelector('h1'), subnav = main.querySelector('.w6-grade-shortcuts .rain-navigation-family__track');
    const styles = getComputedStyle(main);
    return { main: { overflowY: styles.overflowY, padding: styles.padding, height: main.clientHeight, scrollHeight: main.scrollHeight }, heading: { fontSize: getComputedStyle(heading).fontSize, lineHeight: getComputedStyle(heading).lineHeight }, subnavDirection: getComputedStyle(subnav).flexDirection, subnavHeights: [...main.querySelectorAll('.w6-grade-shortcuts .rain-navigation-family__row')].map(row => row.getBoundingClientRect().height), scoreHeight: scorePanel.getBoundingClientRect().height, scoreBackground: getComputedStyle(scorePanel).backgroundColor, scoreSaveEnabledAfterInvalidIdentitySwitch: true };
  });
  await page.screenshot({ path: path.join(out, 'E3-1338x796.png'), fullPage: true });
  await page.setViewportSize({ width: 1200, height: 600 });
  const before = await score.boundingBox();
  findings.grading.shortViewportScroll = await page.locator('[data-scene="E3"] .w6-grade-main').evaluate(main => { main.scrollTop = 200; return { top: main.scrollTop, height: main.clientHeight, scrollHeight: main.scrollHeight }; });
  const after = await score.boundingBox();
  assert.equal(before.y, after.y);
  assert(findings.grading.shortViewportScroll.top > 0);
  findings.grading.scoreStableWhileMainScroll = true;
  await page.setViewportSize({ width: 1338, height: 796 });
  await page.getByRole('link', { name: '课堂回放', exact: true }).click();
  await page.getByRole('button', { name: '播放回放', exact: true }).waitFor();
  const main = page.locator('[data-scene="E4"] .w6-replay-main');
  const mainBefore = await main.boundingBox();
  await page.getByRole('button', { name: '临时查看知识索引', exact: true }).click();
  const mainAfter = await main.boundingBox();
  assert.deepEqual(mainAfter, mainBefore);
  await page.getByRole('button', { name: '控制变量 · 02:10', exact: true }).click();
  await page.keyboard.press('Escape');
  assert.equal(await page.getByTestId('playback-time').textContent(), '02:10');
  findings.replay = await main.evaluate(element => ({ boardGrid: getComputedStyle(element.querySelector('.w6-replay-board')).gridTemplateColumns, boardHeight: element.querySelector('.w6-replay-media').getBoundingClientRect().height, studyGrid: getComputedStyle(element.querySelector('.w6-replay-study-grid')).gridTemplateColumns, headlineSize: getComputedStyle(element.querySelector('h1')).fontSize, samplePanels: element.querySelectorAll('.w6-replay-sample').length, notesSections: element.querySelectorAll('.w6-replay-notes').length, overflowY: getComputedStyle(element).overflowY, temporaryDidNotPushMain: true }));
  await page.screenshot({ path: path.join(out, 'E4-1338x796.png'), fullPage: true });
  assert.deepEqual(faults, []);
  fs.writeFileSync(path.join(out, 'runtime-check.json'), JSON.stringify({ status: 'passed', engine: 'chromium', sourceUrl: 'http://127.0.0.1:5204/navigation-v042-w6-consumer.html', faults, findings }, null, 2));
  console.log(JSON.stringify({ status: 'passed', faults, findings }));
} finally { await browser.close(); }
