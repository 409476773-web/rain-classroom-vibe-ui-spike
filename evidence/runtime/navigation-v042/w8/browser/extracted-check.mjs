import { chromium, expect } from '@playwright/test';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const directory = new URL('../', import.meta.url);
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1600, height: 1100 } });
const errors = [], responses = [];
page.on('pageerror', error => errors.push(String(error)));
page.on('response', response => { if (response.status() >= 400) responses.push({ url: response.url(), status: response.status() }); });
try {
  await page.goto('http://127.0.0.1:5369/#E6');
  const work = page.locator('[data-ai-task="E6"]');
  const draft = work.getByRole('textbox', { name: /审核意见|评审意见/ });
  await draft.fill('解压包独立审核记录');
  await work.getByRole('button', { name: '隐藏资源队列', exact: true }).click();
  await work.getByRole('button', { name: '隐藏评审面板', exact: true }).click();
  await work.getByRole('button', { name: '显示资源队列', exact: true }).click();
  await work.getByRole('button', { name: '显示评审面板', exact: true }).click();
  await expect(draft).toHaveValue('解压包独立审核记录');
  await work.getByRole('button', { name: '保存本地评审', exact: true }).click();
  await expect(work.getByRole('status', { name: '本地保存状态' })).toHaveText('本页已保存');
  await page.evaluate(() => localStorage.setItem('w8-extracted-unrelated', 'retained'));
  await page.getByRole('button', { name: '恢复包内默认', exact: true }).click();
  await expect(draft).toHaveValue('');
  expect(await page.evaluate(() => localStorage.getItem('w8-extracted-unrelated'))).toBe('retained');
  await page.screenshot({ path: fileURLToPath(new URL('E6-extracted-1600.png', import.meta.url)), fullPage: true });
  await page.goto('http://127.0.0.1:5369/#R2');
  const root = page.locator('.nv42-r2-frame');
  await root.getByRole('button', { name: '更多班级', exact: true }).click();
  await page.getByRole('textbox', { name: '搜索范围' }).fill('199');
  await page.getByRole('button', { name: /2026 秋 · 高等数学 199 班/ }).click();
  await expect(root.getByRole('tab', { name: '2026 秋 · 高等数学 199 班', exact: true })).toHaveAttribute('aria-selected', 'true');
  expect(await page.evaluate(() => ['YKT_DEBUG', 'YKT_VISIBILITY', 'vApply'].filter(key => key in window))).toEqual([]);
  expect(errors).toEqual([]); expect(responses).toEqual([]);
  const reportPath = new URL('archive-independent-validation.json', directory);
  const report = JSON.parse(await readFile(reportPath, 'utf8'));
  report.status = 'passed';
  report.sourceCheck = { command: 'node scripts/check-source.mjs --archive-ready', cwd: report.extractionRoot + '/navigation-v042-2026-10-04', exitCode: 0, snapshotId: report.snapshotId };
  report.browser = { engine: 'chromium', version: browser.version(), entry: 'http://127.0.0.1:5369', source: 'extracted built-preview ZIP', checks: ['E6 draft/two-side restore/explicit local save', 'reset restores Mock draft', 'unrelated localStorage retained', 'R2 actual More search selects stable class199', 'no original demo globals'], errors, responses, humanApproved: false, exitCode: 0 };
  report.recordedAt = new Date().toISOString();
  await writeFile(reportPath, JSON.stringify(report, null, 2) + '\n');
  console.log(JSON.stringify({ status: report.status, sourceCheck: report.sourceCheck, browser: report.browser }, null, 2));
} finally { await browser.close(); }
