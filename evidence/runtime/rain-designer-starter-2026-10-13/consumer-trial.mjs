import assert from "node:assert/strict";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { pathToFileURL } from "node:url";

const [consumer, evidence] = process.argv.slice(2);
const { chromium } = await import(pathToFileURL(join(consumer, "node_modules/@playwright/test/index.mjs")).href);
const browser = await chromium.launch({ headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, deviceScaleFactor: 1, colorScheme: "light" });
const errors = [], consoleErrors = [], requests = [];
page.on("pageerror", error => errors.push(error.message));
page.on("console", message => { if (message.type() === "error") consoleErrors.push(message.text()); });
page.on("request", request => requests.push(request.url()));
const checks = [];
try {
  await page.goto("http://127.0.0.1:5543/#bm-a");
  await page.getByRole("heading", { name: "课程资料库", exact: true }).waitFor();
  await page.screenshot({ path: join(evidence, "consumer-desktop.png"), fullPage: true });
  const search = page.getByRole("textbox", { name: "查找资料", exact: true });
  await search.fill("不存在的模拟关键词");
  assert.equal(await page.locator('[data-slot="result-count"]').innerText(), "共 13 份资料");
  checks.push("typing remains a draft");
  await search.press("Enter");
  await page.getByText("没有找到相关资料", { exact: true }).waitFor();
  assert.equal(await page.locator('[data-slot="result-count"]').innerText(), "筛选结果 0 份");
  await page.screenshot({ path: join(evidence, "consumer-empty.png"), fullPage: true });
  checks.push("explicit submit produces no-match empty state");
  await page.getByRole("button", { name: "清空筛选", exact: true }).click();
  assert.equal(await search.inputValue(), "");
  assert.equal(await page.locator('[data-slot="result-count"]').innerText(), "共 13 份资料");
  assert.equal(await search.evaluate(node => node === document.activeElement), true);
  checks.push("reset restores all records and search focus");
  await search.fill("设计方法");
  await page.getByRole("button", { name: "搜索", exact: true }).click();
  assert.equal(await page.locator('[data-slot="result-count"]').innerText(), "筛选结果 1 份");
  const info = page.getByRole("button", { name: "选择规则说明", exact: true });
  await info.click();
  await page.getByText("全选仅作用于当前页可操作资料。翻页或切换视图后，已选资料仍会保留；取消选择会清空所有页的选择。", { exact: true }).waitFor();
  await page.screenshot({ path: join(evidence, "consumer-explanation.png"), fullPage: true });
  await page.keyboard.press("Escape");
  assert.equal(await info.evaluate(node => node === document.activeElement), true);
  assert.equal(await search.inputValue(), "设计方法");
  assert.equal(await page.locator('[data-slot="result-count"]').innerText(), "筛选结果 1 份");
  checks.push("explanation opens and Escape restores focus and retains query");
  await page.getByRole("button", { name: "更多操作 设计方法导论", exact: true }).click();
  await page.getByRole("menuitem", { name: "查看资料", exact: true }).click();
  await page.getByText("正在查看《设计方法导论》；此处为本地演示。", { exact: true }).waitFor();
  assert.equal(await search.inputValue(), "设计方法");
  checks.push("existing material viewing is local feedback only, not a document preview viewer");
  await search.fill("从真实课堂");
  await search.press("Enter");
  await page.getByRole("button", { name: "卡片视图", exact: true }).click();
  await page.getByRole("heading", { name: "从真实课堂问题出发的观察、记录与教学改进：课程资料使用说明", exact: true }).waitFor();
  await page.screenshot({ path: join(evidence, "consumer-long-title.png"), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: join(evidence, "consumer-narrow.png"), fullPage: true });
  const overflow = await page.evaluate(() => ({ viewport: innerWidth, document: document.documentElement.scrollWidth }));
  checks.push("long content and 390px rendering observed; visual judgment recorded separately");
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto("http://127.0.0.1:5543/#bm-a");
  await page.getByRole("heading", { name: "课程资料库", exact: true }).waitFor();
  const cdp = await page.context().newCDPSession(page);
  await cdp.send("DOM.enable");
  await cdp.send("CSS.enable");
  const dom = await cdp.send("DOM.getDocument");
  const fonts = {};
  for (const selector of ["h1", "h2", '[data-rain-id="ui-button"] [data-slot="label"]']) {
    const found = await cdp.send("DOM.querySelector", { nodeId: dom.root.nodeId, selector });
    if (found.nodeId) fonts[selector] = (await cdp.send("CSS.getPlatformFontsForNode", { nodeId: found.nodeId })).fonts;
  }
  assert.deepEqual(errors, []);
  assert.deepEqual(consoleErrors, []);
  assert(requests.every(url => new URL(url).hostname === "127.0.0.1"));
  writeFileSync(join(evidence, "consumer-trial.json"), JSON.stringify({ status: "passed-scoped-interactions", browser: browser.version(), viewport: "1440x1000 and 390x844", dpr: 1, zoom: 1, theme: "light", density: "compact", consumer, url: "http://127.0.0.1:5543/#bm-a", checks, narrowOverflow: overflow, renderedFonts: fonts, pageErrors: errors, consoleErrors, externalRequests: [], contentPreview: "not-present-in-this-existing-scene", pageChanges: [] }, null, 2) + "\n");
  console.log(JSON.stringify({ checks: checks.length, pageErrors: errors, consoleErrors, narrowOverflow: overflow, renderedFonts: fonts }));
} finally { await browser.close(); }
