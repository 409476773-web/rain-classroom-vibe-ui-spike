import { evidenceOutputPath } from "../../scripts/evidence-output.mjs";
import { expect, test } from "@playwright/test";
import { writeFileSync } from "node:fs";
import { contrastRatio } from "./color-contrast";

test("whole-item toggle, selected and disabled siblings, Escape and route rebuilding", async ({ page }) => {
  await page.goto('/#breadcrumb');
  const nav = page.getByRole('navigation', { name: '可交互路径' });
  const arrow = nav.getByRole('button', { name: '切换行政通知的同级页面' });
  await expect(nav.getByRole('link', { name: '行政通知' })).toHaveCount(0);
  await arrow.getByText('行政通知', { exact: true }).hover();
  expect(await arrow.evaluate(node => getComputedStyle(node, '::before').backgroundColor)).toBe('rgba(80, 117, 254, 0.12)');
  await page.getByTestId('siblings').screenshot({ path: evidenceOutputPath('evidence/runtime/breadcrumb/whole-item-hover.png') });
  await arrow.getByText('行政通知', { exact: true }).click();
  await expect(arrow).toHaveAttribute('aria-expanded', 'true');
  await arrow.getByText('行政通知', { exact: true }).click();
  await expect(arrow).toHaveAttribute('aria-expanded', 'false');
  await arrow.focus(); await page.keyboard.press('ArrowDown');
  const menu = page.getByRole('menu');
  await expect(menu.getByRole('menuitem', { name: '行政通知', exact: true })).toHaveAttribute('data-selected', 'true');
  await expect(menu.getByRole('menuitem', { name: '归档通知' })).toHaveAttribute('aria-disabled', 'true');
  await page.keyboard.press('Escape'); await expect(arrow).toBeFocused();
  await arrow.click(); await menu.getByRole('menuitem', { name: '教学通知' }).focus(); await page.keyboard.press('Enter');
  await expect(page.getByTestId('siblings').getByRole('heading', { name: '教学通知', exact: true })).toBeFocused();
  await expect(page).toHaveURL(/breadcrumb-page=teaching/);
  await expect(nav.locator('[aria-current="page"]')).toHaveText('教学通知');
  await expect(nav.getByText('通知详情', { exact: true })).toHaveCount(0);
  await page.getByRole('button', { name: '打开通知详情' }).click();
  await arrow.click();
  await menu.getByRole('menuitem', { name: '行政通知', exact: true }).click();
  await expect(page.getByRole('menu')).toHaveCount(0);
  await expect(nav.locator('[aria-current="page"]')).toHaveText('行政通知');
  await page.reload(); await expect(nav.locator('[aria-current="page"]')).toHaveText('行政通知');
});

test("actual truncation, keyboard tooltip, deep folding and narrow geometry", async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto('/#breadcrumb');
  const basic = page.getByRole('navigation', { name: '基础路径' });
  const link = basic.getByRole('link', { name: '消息中心' });
  await expect(link).toHaveCSS('font-size', '13px'); await expect(link).toHaveCSS('line-height', '18px');
  await expect(link).toHaveCSS('border-radius', '6px');
  expect(await link.evaluate(node => parseFloat(getComputedStyle(node, '::before').height))).toBe(22);
  await expect(link).toHaveCSS('height', '24px'); await expect(link).toHaveCSS('color', 'rgb(86, 104, 143)');
  await expect(basic.locator('[aria-current="page"]')).toHaveCSS('font-weight', '400');
  await expect(basic.locator('[aria-current="page"]')).toHaveCSS('color', 'rgb(20, 35, 70)');
  const facts = await link.evaluate(node => { const style = getComputedStyle(node); return { fontFamily: style.fontFamily, fontSize: style.fontSize, lineHeight: style.lineHeight, height: style.height, color: style.color, background: getComputedStyle(node.closest('.breadcrumb-demo__stage')!).backgroundColor }; });
  const ratio = contrastRatio(facts.color, facts.background, 'rgb(255, 255, 255)');
  expect(ratio).toBeGreaterThanOrEqual(4.5);
  writeFileSync(evidenceOutputPath('evidence/runtime/breadcrumb/browser-facts.json'), JSON.stringify({ ...facts, textContrast: ratio }, null, 2));
  await link.hover();
  expect(await link.evaluate(node => getComputedStyle(node, '::before').backgroundColor)).toBe('rgba(80, 117, 254, 0.12)');
  await page.mouse.down();
  expect(await link.evaluate(node => getComputedStyle(node, '::before').backgroundColor)).toBe('rgba(80, 117, 254, 0.16)');
  await page.mouse.move(0, 0); await page.mouse.up();
  await expect(page.getByRole('tooltip')).toHaveCount(0);
  const current = page.getByRole('navigation', { name: '长名称路径' }).locator('[aria-current="page"]');
  await expect(current).toHaveAttribute('tabindex', '0'); await current.focus(); await page.keyboard.press('Shift+Tab'); await page.keyboard.press('Tab');
  await expect(page.getByRole('tooltip')).toHaveText('关于开展本学期本科教学质量检查与课程材料归档工作的通知');
  const longArrow = page.getByRole('navigation', { name: '长名称路径' }).getByRole('button').last();
  await longArrow.click(); await expect(page.getByRole('tooltip')).toHaveCount(0);
  await expect(page.getByRole('menu')).toBeVisible();
  await page.screenshot({ path: evidenceOutputPath('evidence/runtime/breadcrumb/menu.png'), fullPage: true });
  await page.keyboard.press('Escape');
  const range = page.getByRole('slider', { name: '路径容器宽度' });
  await range.fill('800');
  const deep = page.getByRole('navigation', { name: '深层路径' });
  await expect(deep.locator('ol')).toHaveAttribute('data-collapse', 'none');
  await deep.getByRole('link', { name: '学校管理' }).focus();
  const stage = page.getByTestId('deep').locator('.breadcrumb-demo__resize');
  await stage.evaluate(node => { (node as HTMLElement).style.width = '240px'; });
  await expect(deep.getByRole('button', { name: '查看隐藏的上级路径' })).toBeFocused();
  await expect(deep.locator('ol')).toHaveAttribute('data-collapse', 'tail');
  await deep.getByRole('button', { name: '查看隐藏的上级路径' }).click();
  await expect(page.getByRole('menu').getByRole('menuitem', { name: '工作台' })).toBeVisible();
  await page.keyboard.press('Escape');
  await expect(deep.locator('[aria-current="page"]')).toHaveText('通知详情');
  await stage.evaluate(node => { (node as HTMLElement).style.width = '800px'; });
  await expect(deep.getByRole('link', { name: '工作台' })).toBeFocused();
  await range.fill('400');
  await expect(deep.locator('ol')).toHaveAttribute('data-collapse', 'root');
  await page.screenshot({ path: evidenceOutputPath('evidence/runtime/breadcrumb/desktop.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await expect(deep).toBeVisible();
  await page.screenshot({ path: evidenceOutputPath('evidence/runtime/breadcrumb/narrow.png'), fullPage: true });
  await page.setViewportSize({ width: 320, height: 844 });
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  expect(errors).toEqual([]);
});
