test("loading replaces a stable record and toast exposes action and close", async ({ page }) => {
  await page.getByRole("button", { name: "刷新名单" }).click();
  await expect(page.getByRole("status", { name: /正在/ })).toBeVisible();
  await expect(page.locator(".g2-loading-example")).toHaveCSS("min-height", "96px");
  await expect(page.getByRole("button", { name: "刷新名单" })).toBeDisabled();
  await page.waitForTimeout(800);
  await expect(page.getByText("名单已更新")).toBeVisible();
  await page.getByRole("button", { name: "成功提示" }).click();
  const toast = page.getByRole("dialog");
  await expect(toast).toContainText("设置已保存");
  await page.keyboard.press("F6");
  await expect(toast.getByRole("button", { name: "关闭通知" })).toBeVisible();
  await expect(toast.locator(".rain-g2-toast-close")).toHaveCSS("color", "rgb(255, 255, 255)");
  await expect(toast.locator(".rain-g2-toast-close")).toHaveCSS("opacity", "0.72");
  await page.waitForTimeout(300);
  await page.screenshot({ path: `${evidence}/toast.png` });
  await toast.getByRole("button", { name: "关闭通知" }).click();
  await expect(toast).toBeHidden();
});

test("narrow, dark, reduced motion and forced colors keep the composition usable", async ({ page }) => {
  await page.getByRole("button", { name: "切换深色" }).click();
  await expect(page.locator(".g2")).toHaveAttribute("data-rain-theme", "dark");
  await page.emulateMedia({ reducedMotion: "reduce", forcedColors: "active" });
  await page.setViewportSize({ width: 390, height: 844 });
  await expect(page.getByRole("heading", { name: "显示内容" })).toBeVisible();
  await expect(page.getByRole("heading", { name: "异步反馈" })).toBeVisible();
  await page.screenshot({ path: `${evidence}/narrow-dark-forced-colors.png`, fullPage: true });
});
